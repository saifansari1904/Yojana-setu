export function getLocalizedPathwayAction(
  action: PathwayAction,
  lang: Language = 'en'
): { title: string; description: string; reason: string; cta: string } {
  const match = PATHWAY_ACTION_LOCALIZED[action.id];
  if (match && match[lang]) return match[lang];
  return {
    title: resolveLocalizedPair(action.titleEn, action.titleHi, lang),
    description: resolveLocalizedPair(action.descriptionEn, action.descriptionHi, lang),
    reason: resolveLocalizedPair(action.reasonEn, action.reasonHi, lang),
    cta: resolveLocalizedPair(action.ctaLabelEn, action.ctaLabelHi, lang),
  };
}
