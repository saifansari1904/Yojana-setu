const PREP_STATE_COPY = {
  en: {
    PREPARED: 'Prepared',
    NOT_PREPARED: 'Not prepared',
    UNKNOWN: 'Unknown',
    NOT_REQUIRED: 'Not required',
  },
  hi: {
    PREPARED: 'तैयार',
    NOT_PREPARED: 'तैयार नहीं',
    UNKNOWN: 'अज्ञात',
    NOT_REQUIRED: 'आवश्यक नहीं',
  },
} as const;

const readable = (value?: string): string =>
  value ? value.replace(/_/g, ' ').toLowerCase() : '';

/** Builds the printable report. Pure function — same inputs, same output. */
export const buildPathwayReport = (args: {
  profile: UserProfile | null;
  pathway: SupportPathway;
  matchResults: MatchResult[];
  applications?: TrackedApplication[];
  lang?: 'en' | 'hi';
  generatedAt?: string;
  today?: Date;
}): PathwayReport => {
  const lang = args.lang === 'hi' ? 'hi' : 'en';
  const t = COPY[lang];
  const isHi = lang === 'hi';
  const { profile, pathway } = args;
  const generatedAt = args.generatedAt || new Date().toISOString();
  const today = args.today || new Date(generatedAt);

  const profileLines: ReportLine[] = [
    { label: t.state, value: profile?.state || t.notProvided },
    { label: t.businessType, value: profile?.businessType || t.notProvided },
    { label: t.category, value: profile?.category || t.notProvided },
    {
      label: t.age,
      value: profile?.age !== undefined && profile.age !== null ? String(profile.age) : t.notProvided,
    },
    {
      label: t.income,
      value:
        profile?.annualIncome !== undefined && profile.annualIncome !== null
          ? formatLakhCrore(profile.annualIncome, lang)
          : t.notProvided,
    },
    {
      label: t.primaryNeed,
      value: pathway.primaryNeed ? readable(String(pathway.primaryNeed)) : t.notProvided,
    },
    {
      label: t.secondaryNeeds,
      value:
        pathway.secondaryNeeds.length > 0
          ? pathway.secondaryNeeds.map((need) => readable(String(need))).join(', ')
          : t.none,
    },
  ];

  const fundingLines: ReportLine[] = pathway.funding.hasFundingDetails
    ? [
        {
          label: t.projectCost,
          value: formatLakhCrore(pathway.funding.totalProjectCost, lang),
        },
        {
          label: t.ownInvestment,
          value: formatLakhCrore(pathway.funding.existingInvestment, lang),
        },
        { label: t.fundingGap, value: formatLakhCrore(pathway.funding.fundingGap, lang) },
      ]
    : [];

  const schemeIndex = new Map(args.matchResults.map((m) => [m.scheme.id, m]));

  const schemes: ReportSchemeEntry[] = [];
  pathway.supportStack.forEach((group) => {
    group.schemes.forEach((entry) => {
      const match = schemeIndex.get(entry.schemeId);
      const freshness = match ? evaluateSchemeFreshness(match.scheme, today) : null;
      const lastVerified = entry.provenance.lastVerified;

      schemes.push({
        schemeName: entry.schemeName,
        shortCode: entry.shortCode,
        areaLabel: isHi ? group.labelHi : group.labelEn,
        matchPercentage: entry.matchPercentage,
        matchStatusLabel:
          MATCH_STATUS_COPY[lang][entry.matchStatus as keyof typeof MATCH_STATUS_COPY['en']] ||
          readable(String(entry.matchStatus)),
        source: entry.provenance.source,
        sourceUrl: entry.provenance.sourceUrl,
        lastVerified,
        verificationLine: lastVerified
          ? `${t.verifiedOn} ${lastVerified}${
              freshness?.shouldRecheckOfficialSource
                ? ` — ${isHi ? freshness.labelHi : freshness.labelEn}`
                : ''
            }`
          : t.verificationUnavailable,
      });
    });
  });

  const checklist: ReportChecklistItem[] = pathway.preparationChecklist.items.map((item) => ({
    label: isHi ? item.labelHi : item.labelEn,
    stateLabel:
      PREP_STATE_COPY[lang][item.state as keyof typeof PREP_STATE_COPY['en']] ||
      readable(String(item.state)),
    isMandatory: Boolean(item.isMandatory),
  }));

  const trackedLines: ReportLine[] = (args.applications || []).map((application) => ({
    label: application.schemeName,
    value: application.appliedOn
      ? `${readable(application.status)} — ${application.appliedOn}`
      : readable(application.status) || t.notRecorded,
  }));

  return {
    generatedAt,
    lang,
    title: t.title,
    subtitle: t.subtitle,
    printHint: t.printHint,
    profileLines,
    journeyLine: {
      label: t.stage,
      value: isHi ? pathway.currentStageLabelHi : pathway.currentStageLabelEn,
    },
    priorityLabels: pathway.recommendedSupportAreas
      .slice(0, 5)
      .map((area) => (isHi ? area.labelHi : area.labelEn)),
    nextAction: {
      title: isHi ? pathway.nextBestAction.titleHi : pathway.nextBestAction.titleEn,
      reason: isHi ? pathway.nextBestAction.reasonHi : pathway.nextBestAction.reasonEn,
      cta: isHi ? pathway.nextBestAction.ctaLabelHi : pathway.nextBestAction.ctaLabelEn,
    },
    readiness: {
      stateLabel: isHi ? pathway.readiness.labelHi : pathway.readiness.labelEn,
      summary: isHi ? pathway.readiness.summaryHi : pathway.readiness.summaryEn,
      checks: pathway.readiness.checks.map((check) => ({
        label: isHi ? check.labelHi : check.labelEn,
        value: isHi ? check.detailHi : check.detailEn,
      })),
    },
    schemes,
    checklist,
    fundingLines,
    trackedLines,
    disclaimers: [...t.disclaimers],
  };
};
