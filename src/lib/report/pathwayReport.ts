/**
 * PHASE 4.3 — SHAREABLE PATHWAY REPORT
 *
 * Builds a print-ready, plain-data snapshot of the citizen's support pathway,
 * suitable for taking to a bank branch, DIC office or CSC.
 *
 * Rules:
 *  - Reuses Phase 4.2 pathway output and Phase 3.1 match results as-is.
 *  - No new calculations, no AI, no invented scheme facts.
 *  - Every listed scheme keeps its official source and verification line.
 *  - No amount is presented as assured government assistance.
 */

